static int K33LocKnownCaller(DWORD address)
{
    for (unsigned i=0;i<sizeof(kK33LocSites)/sizeof(kK33LocSites[0]);i++)
        if (address==kK33LocSites[i].return_address) return 1;
    return 0;
}

static int K33LocWritable(void *data,size_t length)
{
    MEMORY_BASIC_INFORMATION info;uintptr_t cursor=(uintptr_t)data;
    if (!data || length>UINTPTR_MAX-cursor) return 0;
    uintptr_t end=cursor+length;
    while (cursor<end) {
        if (!VirtualQuery((void *)cursor,&info,sizeof(info)) || info.State!=MEM_COMMIT ||
            (info.Protect&(PAGE_GUARD|PAGE_NOACCESS)) ||
            !(info.Protect&(PAGE_READWRITE|PAGE_WRITECOPY|PAGE_EXECUTE_READWRITE|PAGE_EXECUTE_WRITECOPY))) return 0;
        uintptr_t next=(uintptr_t)info.BaseAddress+info.RegionSize;
        if (next<=cursor) return 0;
        cursor=next<end ? next:end;
    }
    return 1;
}

static int K33LocReadable(const void *data,size_t length)
{
    MEMORY_BASIC_INFORMATION info;uintptr_t cursor=(uintptr_t)data;
    if (!data || length>UINTPTR_MAX-cursor) return 0;
    uintptr_t end=cursor+length;
    while (cursor<end) {
        if (!VirtualQuery((const void *)cursor,&info,sizeof(info)) || info.State!=MEM_COMMIT ||
            (info.Protect&(PAGE_GUARD|PAGE_NOACCESS)) ||
            !(info.Protect&(PAGE_READONLY|PAGE_READWRITE|PAGE_WRITECOPY|PAGE_EXECUTE_READ|
                             PAGE_EXECUTE_READWRITE|PAGE_EXECUTE_WRITECOPY))) return 0;
        uintptr_t next=(uintptr_t)info.BaseAddress+info.RegionSize;
        if (next<=cursor) return 0;
        cursor=next<end ? next:end;
    }
    return 1;
}

static int K33LocViewOf(const char *text,K33LocView *view)
{
    uintptr_t cursor=(uintptr_t)text;size_t length=0;
    view->data=NULL;view->length=0;
    if (!text) return 0;
    while (length<K33LOC_INPUT_LIMIT) {
        MEMORY_BASIC_INFORMATION info;
        if (!VirtualQuery((const void *)cursor,&info,sizeof(info)) || info.State!=MEM_COMMIT ||
            (info.Protect&(PAGE_GUARD|PAGE_NOACCESS)) ||
            !(info.Protect&(PAGE_READONLY|PAGE_READWRITE|PAGE_WRITECOPY|PAGE_EXECUTE_READ|
                             PAGE_EXECUTE_READWRITE|PAGE_EXECUTE_WRITECOPY))) return 0;
        uintptr_t end=(uintptr_t)info.BaseAddress+info.RegionSize;
        if (end<=cursor) return 0;
        size_t scan=end-cursor;
        if (scan>K33LOC_INPUT_LIMIT-length) scan=K33LOC_INPUT_LIMIT-length;
        const char *nul=memchr((const void *)cursor,0,scan);
        if (nul) { view->data=text;view->length=length+(size_t)((uintptr_t)nul-cursor);return 1; }
        length+=scan;cursor+=scan;
    }
    return 0;
}

static void __attribute__((cdecl,noinline,force_align_arg_pointer)) K33LocReplacement(const char *format,const K33LocArgs *args,char *output)
{
    if (!K33LocKnownCaller(K33LOC_CALLER())) {
        if (K33LocWritable(output,1)) output[0]=0;
        return;  /* No unreviewed capacity/caller receives native fallback. */
    }
    if (!K33LocWritable(output,K33LOC_CAPACITY)) return;
    memset(output,0,K33LOC_CAPACITY);
    K33LocView text,values[K33LOC_MAX_ARGS];int count=0;
    memset(values,0,sizeof(values));
    if (!K33LocViewOf(format,&text)) return;
    if (args) {
        if (!K33LocReadable(args,sizeof(*args)) || args->count<0 || args->count>(int)K33LOC_MAX_ARGS) return;
        count=args->count;
        for (int i=0;i<count;i++) K33LocViewOf(args->values[i],&values[i]);
    }
    K33LocFormat(text,values,count,output,K33LOC_CAPACITY);
}

static int K33LocGuards(void)
{
    const void *target=K33LOC_AT(0x005f4de0u);
    if (!K33LocReadable(target,sizeof(kK33LocOriginal)) || memcmp(target,kK33LocOriginal,sizeof(kK33LocOriginal))) return 0;
    for (unsigned i=0;i<sizeof(kK33LocSites)/sizeof(kK33LocSites[0]);i++) {
        const K33LocSite *site=&kK33LocSites[i];const void *at=K33LOC_AT(site->address);
        if (!K33LocReadable(at,site->size) || memcmp(at,site->bytes,site->size)) return 0;
    }
    /* Pin each caller from its frame allocation through this call. This binds
     * the reviewed capacity and argument construction, not only the call E8. */
    for (unsigned i=0;i<sizeof(kK33LocFrames)/sizeof(kK33LocFrames[0]);i++) {
        const K33LocSite *site=&kK33LocFrames[i];const void *at=K33LOC_AT(site->address);
        if (!K33LocReadable(at,site->size) || memcmp(at,site->bytes,site->size)) return 0;
    }
    return 1;
}

static int InstallBoundedLocalizedSubstitution(void)
{
    if (!K33LocGuards()) return 0;
    BYTE patch[6]={0xe9,0,0,0,0,0x90};DWORD previous,ignored;
    void *target=K33LOC_AT(0x005f4de0u);
    LONG relative=(LONG)((uintptr_t)K33LocReplacement-((uintptr_t)target+5));
    memcpy(patch+1,&relative,4);
    if (!VirtualProtect(target,sizeof(patch),PAGE_EXECUTE_READWRITE,&previous)) return 0;
    memcpy(target,patch,sizeof(patch));
    int matched=!memcmp(target,patch,sizeof(patch));
    int flushed=FlushInstructionCache(GetCurrentProcess(),target,sizeof(patch));
    int restored=VirtualProtect(target,sizeof(patch),previous,&ignored);
    return matched && flushed && restored;
}
