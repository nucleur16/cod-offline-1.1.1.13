"""Generate c1_tables.h: the import slots C1.dll fills in C1.exe (1.1.1.13).

C1.dll builds a table of {slot VA, function name, DLL name} in one long function: for each
entry it pushes the name string, stores the slot address with `mov [ebp-X], slot`, then pushes
the DLL string. We walk that code and read the triples back out.

    python Kernel33/gen_tables.py
"""
import os
import re

import capstone
import pefile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def c1dll_imports(path):
    pe = pefile.PE(path)
    base = pe.OPTIONAL_HEADER.ImageBase
    img = pe.get_memory_mapped_image()
    text = [s for s in pe.sections if s.Name.startswith(b".text")][0]
    rdata_lo, rdata_hi = base + 0xA000, base + 0x10000

    def cstr(va):
        o = va - base
        return img[o:img.index(b"\0", o)].decode("latin1")

    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    seq = []
    for i in md.disasm(text.get_data(), base + text.VirtualAddress):
        if i.mnemonic == "push" and i.op_str.startswith("0x"):
            v = int(i.op_str, 16)
            if rdata_lo <= v < rdata_hi:
                seq.append(("s", cstr(v)))
        m = re.match(r"dword ptr \[ebp - 0x[0-9a-f]+\], (0x[0-9a-f]+)$", i.op_str)
        if i.mnemonic == "mov" and m:
            v = int(m.group(1), 16)
            if 0x401000 <= v < 0x9A30000:
                seq.append(("slot", v))

    out, k = [], 0
    while k < len(seq):
        if (seq[k][0] == "slot" and 0 < k < len(seq) - 1 and seq[k - 1][0] == "s" and seq[k + 1][0] == "s"):
            a, b = seq[k - 1][1], seq[k + 1][1]
            # usually name, slot, dll; for some entries the compiler emits the DLL first
            dll, name = (b, a) if b.lower().endswith((".dll", ".drv")) else (a, b)
            if not dll.lower().endswith((".dll", ".drv")) or name.lower().endswith(".dll"):
                raise SystemExit("cannot tell DLL from function at slot %#x: %r %r" % (seq[k][1], a, b))
            out.append((seq[k][1], dll, name))
            k += 2
        else:
            k += 1
    slots = sum(1 for x in seq if x[0] == "slot")
    if len(out) != slots:
        raise SystemExit("parsed %d of %d slots from C1.dll" % (len(out), slots))
    return out


def main():
    imports = c1dll_imports(os.path.join(ROOT, "C1.dll"))
    lines = [
        "/* Generated by gen_tables.py from C1.dll: the import slots it fills in C1.exe.",
        " * Build 1.1.1.13 (PE timestamp 0x5314DEF0) only. */",
        "",
        "typedef struct { DWORD slot; const char *dll; const char *name; } C1Import;",
        "static const C1Import kC1Imports[] = {",
    ]
    lines += ['    { 0x%08X, "%s", "%s" },' % imp for imp in imports]
    lines += ["};", ""]
    with open(os.path.join(HERE, "c1_tables.h"), "w", newline="\n") as f:
        f.write("\n".join(lines))
    print("c1_tables.h: %d imports" % len(imports))


if __name__ == "__main__":
    main()
