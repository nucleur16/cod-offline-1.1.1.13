#!/usr/bin/env python3
"""Writes src/offline/dw_tiger_sboxes.h from the Python lobby's demonware/tiger_sboxes.py.

    python src/offline/tools/gen_tiger_sboxes.py <python-lobby-root>

The tables are the public Tiger/192 S-boxes (Anderson & Biham, 1996), 4 x 256 u64.
"""
import importlib.util
import os
import sys


def main():
    root = sys.argv[1]
    spec = importlib.util.spec_from_file_location("tiger_sboxes", os.path.join(root, "demonware", "tiger_sboxes.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "dw_tiger_sboxes.h")
    with open(out, "w", newline="\n") as fh:
        fh.write("/* Generated by src/offline/tools/gen_tiger_sboxes.py: the public Tiger/192 S-boxes. */\n")
        for name in ("T1", "T2", "T3", "T4"):
            table = getattr(mod, name)
            assert len(table) == 256
            fh.write("static const unsigned long long kTiger%s[256] = {\n" % name)
            for i in range(0, 256, 4):
                fh.write("    " + ", ".join("0x%016XULL" % v for v in table[i:i + 4]) + ",\n")
            fh.write("};\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
