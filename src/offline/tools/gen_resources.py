#!/usr/bin/env python3
"""Writes src/offline/dw_embedded.cpp: the resources the offline lobby serves or reads at run time.

    python src/offline/tools/gen_resources.py <python-lobby-root> [--check]

The files come from the Python lobby's resources/ folder (CODOL-EMU 1.1.1.13 Demonware emulator:
tables harvested from the client's own zones, seed blobs, the publisher .info files). The list is
src/offline/resources.manifest - one name per line, `name = other/path` to take the bytes from another
path under the lobby root, `name = py:<module path>:<symbol>` to take a table the Python lobby keeps as
a string constant in a module (rendered by RENDERERS below), `name = repo:<path>` to take a file of THIS
repository (where the product differs from the Python lobby on purpose). Each file is stored zlib-compressed
unless that does not make it smaller.

A file dropped into <store>\\resources\\ at run time overrides its embedded copy (Server::Resource).
--check regenerates in memory and fails when src/offline/dw_embedded.cpp is out of date.
"""
import os
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
OFFLINE = os.path.dirname(HERE)
#: reported as the pubfile modifiedTime (the client only needs "non-zero and stable").
EMBED_MTIME = 1762905600  # 2025-11-12 00:00:00 UTC


def manifest():
    out = []
    with open(os.path.join(OFFLINE, "resources.manifest"), encoding="utf-8") as fh:
        for line in fh:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            name, _, src = (p.strip() for p in line.partition("="))
            out.append((name, src or os.path.join("resources", name)))
    return out


def attach_table_text(raw):
    """catalogue/weapon_tables.py _ATTACH_RAW ("weapon:att[=variant],...;weapon:...") as one line per
    weapon, `weapon att[=variant] att ...`, in the table's own order: mp/coWeaponAttachmentTable.csv as
    the client and the match server read it (catalogue.weapon_loadout.attach_table)."""
    lines = []
    for chunk in raw.split(";"):
        name, _, items = chunk.partition(":")
        if name:
            lines.append(" ".join([name] + [it for it in items.split(",") if it]))
    return ("\n".join(lines) + "\n").encode("ascii")


RENDERERS = {"_ATTACH_RAW": attach_table_text}


def read_source(root, src):
    if src.startswith("py:"):
        import runpy
        _, path, symbol = src.split(":", 2)
        return RENDERERS[symbol](runpy.run_path(os.path.join(root, path))[symbol])
    if src.startswith("repo:"):
        root, src = os.path.dirname(os.path.dirname(OFFLINE)), src[5:]
    with open(os.path.join(root, src), "rb") as fh:
        return fh.read()


def render(root):
    parts = ["/* Generated by src/offline/tools/gen_resources.py from the Python lobby's resources - do not edit. */\n",
             '#include "dw_state.h"\n\nnamespace dw {\n\n']
    table, total_raw, total_packed = [], 0, 0
    for idx, (name, src) in enumerate(manifest()):
        raw = read_source(root, src)
        packed = zlib.compress(raw, 9)
        use_packed = len(packed) < len(raw)
        data = packed if use_packed else raw
        total_raw += len(raw)
        total_packed += len(data)
        parts.append("static const unsigned char kRes%d[] = {" % idx)
        if not data:
            parts.append("0")
        for i in range(0, len(data), 32):
            parts.append("\n" + ",".join(str(b) for b in data[i:i + 32]) + ("," if i + 32 < len(data) else ""))
        parts.append("\n};\n")
        table.append('    { "%s", kRes%d, %d, %d, %d, %dLL },\n' % (
            name, idx, len(raw), len(data), 1 if use_packed else 0, EMBED_MTIME))
    parts.append("\nconst EmbeddedFile kEmbedded[] = {\n" + "".join(table) + "};\n")
    parts.append("const int kEmbeddedCount = %d;\n\n} // namespace dw\n" % len(table))
    return "".join(parts), len(table), total_raw, total_packed


def main():
    root = sys.argv[1]
    text, n, raw, packed = render(root)
    out = os.path.join(OFFLINE, "dw_embedded.cpp")
    if "--check" in sys.argv:
        with open(out, encoding="utf-8") as fh:
            if fh.read() != text:
                sys.exit("offline/dw_embedded.cpp is out of date: run gen_resources.py")
        print("dw_embedded.cpp is current (%d files)" % n)
        return
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s: %d files, %d bytes raw, %d embedded" % (out, n, raw, packed))


if __name__ == "__main__":
    main()
